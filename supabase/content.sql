create table if not exists public.subjects (
  id         int generated by default as identity primary key,
  name       text not null unique check (char_length(name) between 2 and 80),
  created_at timestamptz not null default now()
);

create table if not exists public.reviewers (
  id          int generated by default as identity primary key,
  title       text not null check (char_length(title) between 3 and 120),
  subject     text not null references public.subjects(name) on update cascade on delete restrict,
  year_level  int  not null default 1 check (year_level between 1 and 4),
  section     text check (char_length(section) <= 20),
  sem         int  not null default 1 check (sem in (1, 2)),
  exam        text not null check (exam in ('Prelim', 'Midterm', 'Semi-Final', 'Final')),
  file_type   text not null check (file_type in ('PDF', 'DOCX', 'PPTX')),
  file_size   text,
  uploaded_by text,
  topics      text[] not null default '{}',
  downloads   int  not null default 0,
  created_at  timestamptz not null default now()
);
create index if not exists reviewers_subject_idx on public.reviewers (subject);

create table if not exists public.exams (
  id         int generated by default as identity primary key,
  title      text not null check (char_length(title) between 3 and 120),
  subject    text not null references public.subjects(name) on update cascade on delete restrict,
  diff       text not null default 'Medium' check (diff in ('Easy', 'Medium', 'Hard')),
  mins       int  not null default 10 check (mins between 1 and 300),
  pass       int  not null default 60 check (pass between 1 and 100),
  questions  jsonb not null default '[]',
  created_at timestamptz not null default now()
);
create index if not exists exams_subject_idx on public.exams (subject);

-- Row Level Security
-- Read: any signed-in user. Add/edit: moderator + admin. Delete: admin only.
alter table public.subjects  enable row level security;
alter table public.reviewers enable row level security;
alter table public.exams     enable row level security;

do $$
declare t text;
begin
  foreach t in array array['subjects', 'reviewers', 'exams'] loop
    execute format('drop policy if exists "read %1$s" on public.%1$s', t);
    execute format('drop policy if exists "staff add %1$s" on public.%1$s', t);
    execute format('drop policy if exists "staff edit %1$s" on public.%1$s', t);
    execute format('drop policy if exists "admin delete %1$s" on public.%1$s', t);
    execute format('create policy "read %1$s" on public.%1$s for select to authenticated using (true)', t);
    execute format('create policy "staff add %1$s" on public.%1$s for insert to authenticated with check (public.my_role() in (''moderator'', ''admin''))', t);
    execute format('create policy "staff edit %1$s" on public.%1$s for update to authenticated using (public.my_role() in (''moderator'', ''admin'')) with check (public.my_role() in (''moderator'', ''admin''))', t);
    execute format('create policy "admin delete %1$s" on public.%1$s for delete to authenticated using (public.my_role() = ''admin'')', t);
  end loop;
end $$;

-- Download counter (students cannot edit reviewers, so this runs with elevated rights)
create or replace function public.bump_download(rid int) returns void
language sql security definer set search_path = public as $$
  update public.reviewers set downloads = downloads + 1 where id = rid
$$;
revoke all on function public.bump_download(int) from public, anon;
grant execute on function public.bump_download(int) to authenticated;

